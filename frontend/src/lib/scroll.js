import { nextTick } from 'vue';

// Периодический поллинг (активен драфт / парсится демка / включён автосинк
// Google Sheets) переприсваивает реактивные данные целиком, и после такого
// ре-рендера браузер иногда сбрасывал скролл страницы в начало — особенно
// заметно на странице живого драфта, где обновление идёт каждые 2.5–3 сек.
// Оборачиваем сам рефетч: запоминаем scrollY до, дожидаемся, пока DOM
// обновится после присвоения новых данных (nextTick), и восстанавливаем
// прежнюю позицию.
export async function withScrollPreserved(fn) {
  const y = window.scrollY;
  try {
    return await fn();
  } finally {
    await nextTick();
    window.scrollTo(0, y);
  }
}
